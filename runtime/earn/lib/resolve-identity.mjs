// resolve-identity.mjs — per-instance multi-chain identity resolution (#26 EQUALIZE).
//
// The real unequalizer was never identity GENERATION (every instance already gets its own
// EVM + Solana keypair — runtime/compute-proxy/start-local.sh + ensure-solana-wallet.mjs) or
// SLOT access (every instance sees the same live pm/sol/hl slots — earn-slot.mjs). It is that
// each trading engine hardcodes a fixed wallet source (pm-trade → claude-p's agent .env,
// sol-trade → Franklin's ~/.blockrun/.solana-session). This module gives every engine ONE
// place to ask "what is THIS instance's own key" so a fresh spawn can trade with its OWN
// identity, while an existing instance's current resolution path is preserved unchanged.
//
// Priority order (spec 2026-07-05-equalize-multichain-identity-design.md R1/R2; flat-layout
// fallback added 2026-07-10 -- see gh issue #986, dozens of pre-EQUALIZE instances (e.g.
// founder-loop's ~/.anicca-founder) were generated by the original wallet-gen script straight
// into $ANICCA_HOME/wallet.json, never migrated under .automaton/, and were fail-closed HALTing
// on every earn action as a result):
//   EVM:    ① env.ANICCA_EVM_PRIVATE_KEY  ② $ANICCA_HOME/.automaton/wallet.json (privateKey)
//           ③ $ANICCA_HOME/wallet.json (flat legacy layout, private_key|privateKey field)
//           ④ $HOME/.automaton/wallet.json (back-compat, legacy shared path)  ⑤ null
//   Solana: ① env.ANICCA_SOLANA_PRIVATE_KEY  ② $ANICCA_HOME/.automaton/solana.json (secretKey)
//           ③ $ANICCA_HOME/solana-wallet.json (flat legacy layout, secret_key_base58|secretKey)
//           ④ $HOME/.blockrun/.solana-session (back-compat, Franklin's legacy path)  ⑤ null
//
// Fail-closed (R5, money-safety): any missing file/field or parse error returns null — this
// module NEVER throws. Callers (run.sh wrappers) must treat null as "skip this engine, warn".
// This module never logs/echoes the key material it reads or returns — that discipline stays
// with the caller (see env-filter.mjs's scrubPrivateKeys / redactPrivateKeyPatterns).

import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

// Reads `field` out of a JSON file. Returns null (never throws) on any read/parse/shape issue.
function readJsonField(filePath, field) {
  try {
    const parsed = JSON.parse(fs.readFileSync(filePath, 'utf8'));
    const value = parsed && parsed[field];
    return typeof value === 'string' && value.length > 0 ? value : null;
  } catch {
    return null;
  }
}

// Reads a raw single-value secret file (e.g. Franklin's `.solana-session`: a bare base58
// string, no JSON wrapper). Returns null (never throws) on any read issue or empty content.
function readRawSecretFile(filePath) {
  try {
    const raw = fs.readFileSync(filePath, 'utf8').trim();
    return raw.length > 0 ? raw : null;
  } catch {
    return null;
  }
}

// viem's generatePrivateKey() already returns a `0x`-prefixed key, but normalize defensively
// (matches the existing convention in skills/earn/ensure-gas.mjs's loadKey()).
function normalizeEvmKey(key) {
  if (typeof key !== 'string' || key.length === 0) return null;
  return key.startsWith('0x') ? key : `0x${key}`;
}

/**
 * Resolve THIS instance's own EVM signing key (immutable, pure read — no mutation, no throw).
 *
 * @param {{home?: string, env?: Record<string, string>}} [opts]
 *   home: explicit ANICCA_HOME override (mainly for tests); defaults to opts.env.ANICCA_HOME.
 *   env:  environment map to read overrides/back-compat HOME from; defaults to process.env.
 * @returns {string|null} `0x`-prefixed private key, or null if unresolvable (fail-closed).
 */
export function resolveEvmPrivateKey({ home, env } = {}) {
  const e = env || process.env;

  const override = normalizeEvmKey(e.ANICCA_EVM_PRIVATE_KEY);
  if (override) return override;

  // Effective home mirrors resolve-wallet-path.sh: explicit ANICCA_HOME, else default $HOME/.anicca.
  const effectiveHome = home ?? e.ANICCA_HOME ?? (e.HOME ? path.join(e.HOME, '.anicca') : null);
  if (effectiveHome) {
    const fromHome = readJsonField(path.join(effectiveHome, '.automaton', 'wallet.json'), 'privateKey');
    if (fromHome) return normalizeEvmKey(fromHome);

    // Flat legacy layout (gh #986): this instance's OWN key at $ANICCA_HOME/wallet.json directly,
    // never migrated under .automaton/. Still scoped strictly to effectiveHome -- same fail-closed,
    // own-instance-only guarantee as the .automaton path above (never reads another instance's home).
    const fromFlatHome = readJsonField(path.join(effectiveHome, 'wallet.json'), 'private_key')
      || readJsonField(path.join(effectiveHome, 'wallet.json'), 'privateKey');
    if (fromFlatHome) return normalizeEvmKey(fromFlatHome);
  }

  // Legacy shared $HOME/.automaton/wallet.json is the ORIGINAL default-home instance's wallet. Resolve
  // it ONLY for that owner (effectiveHome === $HOME/.anicca), exactly like resolve-wallet-path.sh. A
  // spawn with a different home returns null (fail-closed) so it NEVER trades with another instance's
  // key — this is the real trading-key path used by pm-trade/run.sh (FIND-001-class, round-2).
  const legacyHome = e.HOME;
  if (legacyHome && effectiveHome === path.join(legacyHome, '.anicca')) {
    const fromLegacy = readJsonField(path.join(legacyHome, '.automaton', 'wallet.json'), 'privateKey');
    if (fromLegacy) return normalizeEvmKey(fromLegacy);
  }

  return null;
}

/**
 * The EVM key loader every earn skill / util uses (#28). Preserves the loop's per-instance env
 * convention: a named env key wins (PKVAR indirection or BLOCKRUN_WALLET_KEY), else the GATED
 * per-instance file resolution (resolveEvmPrivateKey — EFFECTIVE_HOME first, legacy only for the
 * rightful owner, foreign spawn → null). Returns a 0x-prefixed key or null. Callers MUST treat null
 * as fail-closed (abort/skip) — NEVER read $HOME/.automaton/wallet.json directly, which let a foreign
 * spawn sign with another instance's money key.
 *
 * @param {{env?: Record<string, string>}} [opts]
 * @returns {string|null}
 */
export function loadEvmKey({ env } = {}) {
  const e = env || process.env;
  const named = (e.PKVAR && e[e.PKVAR]) || e.BLOCKRUN_WALLET_KEY;
  if (named) return normalizeEvmKey(named);
  return resolveEvmPrivateKey({ env: e });
}

/**
 * Resolve THIS instance's own Solana signing secret (base58, immutable, pure read — no throw).
 *
 * @param {{home?: string, env?: Record<string, string>}} [opts]
 *   home: explicit ANICCA_HOME override (mainly for tests); defaults to opts.env.ANICCA_HOME.
 *   env:  environment map to read overrides/back-compat HOME from; defaults to process.env.
 * @returns {string|null} base58 secret key, or null if unresolvable (fail-closed).
 */
export function resolveSolanaSecret({ home, env } = {}) {
  const e = env || process.env;

  if (typeof e.ANICCA_SOLANA_PRIVATE_KEY === 'string' && e.ANICCA_SOLANA_PRIVATE_KEY.length > 0) {
    return e.ANICCA_SOLANA_PRIVATE_KEY;
  }

  const effectiveHome = home ?? e.ANICCA_HOME ?? (e.HOME ? path.join(e.HOME, '.anicca') : null);
  if (effectiveHome) {
    const fromHome = readJsonField(path.join(effectiveHome, '.automaton', 'solana.json'), 'secretKey');
    if (fromHome) return fromHome;

    // Flat legacy layout (gh #986): this instance's OWN secret at $ANICCA_HOME/solana-wallet.json
    // directly, never migrated under .automaton/. Scoped strictly to effectiveHome, symmetric with
    // the EVM flat-layout fallback above.
    const fromFlatHome = readJsonField(path.join(effectiveHome, 'solana-wallet.json'), 'secret_key_base58')
      || readJsonField(path.join(effectiveHome, 'solana-wallet.json'), 'secretKey');
    if (fromFlatHome) return fromFlatHome;
  }

  // Legacy $HOME/.blockrun/.solana-session is Franklin's OWN funded wallet. Resolve it ONLY for
  // Franklin's home (effectiveHome === $HOME/.blockrun); a different spawn returns null (fail-closed)
  // so it never signs with Franklin's key (FIND-001-class, round-2, symmetric with the EVM path).
  const legacyHome = e.HOME;
  if (legacyHome && effectiveHome === path.join(legacyHome, '.blockrun')) {
    const fromSession = readRawSecretFile(path.join(legacyHome, '.blockrun', '.solana-session'));
    if (fromSession) return fromSession;
  }

  return null;
}

// --- CLI entrypoint: `node resolve-identity.mjs <evm|solana>` prints the resolved key to
// stdout (nothing if unresolved) so bash run.sh wrappers can capture it via command
// substitution — this module itself never logs the key (R5 + env-filter discipline).
if (process.argv[1] && path.resolve(process.argv[1]) === fileURLToPath(import.meta.url)) {
  const which = process.argv[2];
  if (which === 'evm-address') {
    // Derive the EVM address via viem — NOT python/eth_account. run.sh's old python one-liner
    // silently returned '' under launchd's clean PATH (no eth_account on sys.path), so a free
    // Franklin's x402 wake HALTed with wallet='' even though its key resolved fine (x402-zero-to-one
    // 2026-07-14). node+viem is already a hard dep of the seller, so it's always present.
    const key = resolveEvmPrivateKey({});
    if (key) {
      const { privateKeyToAccount } = await import('viem/accounts');
      process.stdout.write(privateKeyToAccount(key).address + '\n');
    }
  } else if (which !== 'evm' && which !== 'solana') {
    process.stderr.write('usage: resolve-identity.mjs <evm|evm-address|solana>\n');
    process.exitCode = 2;
  } else {
    const resolved = which === 'evm' ? resolveEvmPrivateKey({}) : resolveSolanaSecret({});
    if (resolved) process.stdout.write(resolved + '\n');
  }
}
